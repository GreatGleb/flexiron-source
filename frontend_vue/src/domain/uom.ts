import type { Uom } from '@/types/settings'
import type { TranslatedString } from '@/types/i18n'

/**
 * Подпись единицы измерения — единственное место, где она собирается.
 *
 * До 2026-08-27 систем было две (пункт 4c плана `review-followups.md`):
 * справочник настроек, где у каждой единицы есть свой код на трёх языках
 * (`шт` / `pcs` / `vnt`), и семейство ключей `orders.unit_*` в модуле заказов.
 * Источником выбран СПРАВОЧНИК, и вот почему:
 *
 *   - ключей было пять на девять единиц, а второй аргумент `t()` — это дефолт,
 *     поэтому единица без ключа молча рисовалась своим id-кодом на всех трёх
 *     языках. Расширять такую систему значит заводить по ключу на каждую строку
 *     справочника вручную и узнавать о пропуске от пользователя;
 *   - справочник редактируется в настройках, а ключи — только правкой кода:
 *     единица, заведённая пользователем, подписи в заказах не получила бы никогда;
 *   - и он уже был источником де-факто: тем же правилом подписаны услуги
 *     (`serviceUnitLabel`), карточка товара и модалка добавления позиций.
 *
 * Строка заказа хранит единицу кодом без префикса (`'pcs'`), потому что мок
 * собирает её как `saleUomId.replace(/^uom-/, '')` — то есть это тот же id, у
 * которого срезали начало. Поэтому здесь принимается и `'pcs'`, и `'uom-pcs'`:
 * это не два формата, а один и его огрызок. Огрызок исчезнет вместе с п. 4d,
 * когда величина везде станет ссылкой на справочник.
 */
export function uomCode(unit: string, uoms: Uom[], locale: string): string | null {
  const id = unit.startsWith('uom-') ? unit : `uom-${unit}`
  const uom = uoms.find((u) => u.id === id)
  if (!uom) return null
  const key = locale as keyof TranslatedString
  return uom.code[key] || uom.code.en || uom.code.ru || null
}

/**
 * Подпись единицы для показа. Справочник ещё не загружен или единицы в нём нет —
 * показываем сам код: он короткий и узнаваемый, а прочерк на месте килограммов
 * читается как «единицы нет», что неправда.
 */
export function unitLabel(unit: string | null | undefined, uoms: Uom[], locale: string): string {
  if (!unit) return '—'
  return uomCode(unit, uoms, locale) ?? unit
}

/**
 * Код единицы, каким его ХРАНИТ строка заказа: id справочника без префикса.
 *
 * Отдельная функция, потому что это не подпись, а данные, и путать их дорого:
 * модалка добавления позиций до 2026-08-27 клала сюда результат перевода, то есть
 * в русском сеансе строка заказа получала `unit: 'шт'`. Тот же дефект, что в
 * п. 4b плана, только на месяц раньше по пути данных — англичанин увидел бы `шт`
 * в чужом заказе, и никакая подпись это уже не чинит.
 */
export function orderLineUnit(uomId: string | null | undefined): string {
  if (!uomId) return 'pcs'
  return uomId.replace(/^uom-/, '')
}
