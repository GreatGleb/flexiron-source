/**
 * Условия оплаты клиента — отсрочка в днях от даты счёта.
 *
 * Почему число дней, а не свободная строка, какой это поле у поставщика
 * (`SupplierCardData.paymentTerms` = `'30 Days Net'`): из условий клиента должен
 * считаться срок оплаты счёта — пункт 9 плана `review-followups.md` называет это
 * прямо, а пункт 13 §5 на этом строит реестр входящих («срок оплаты берётся из
 * условий оплаты клиента, а не вводится руками»). Из строки `'30 Days Net'` дату
 * не получить ничем, кроме разбора регуляркой, то есть той же разнописи, которую
 * пункты 4c–4e вычищали из единиц и имён товаров.
 *
 * Ноль — законное значение: оплата по счёту, без отсрочки. Поэтому поле
 * обязательное и не nullable — «не заполнено» здесь неотличимо от «платит сразу»,
 * а неотличимость и есть та дыра, через которую условия молча теряются.
 */

/** Годится ли значение как условия оплаты: целое число дней, не отрицательное. */
export function isValidPaymentTermsDays(value: unknown): value is number {
  return typeof value === 'number' && Number.isInteger(value) && value >= 0
}

/**
 * Приводит то, что ввели в поле, к целым неотрицательным дням.
 *
 * `v-model.number` на очищенном поле кладёт `NaN` (питфолл #25), а `type="number"`
 * пропускает и минус, и дробь — браузерный `min="0"` только рисует, но не запрещает.
 * Отрицательная отсрочка датировала бы счёт задним числом, то есть просроченным в
 * день выставления; дробная — сроком в середине дня, которого календарь не знает.
 */
export function normalizePaymentTermsDays(value: unknown): number {
  const days = typeof value === 'number' ? value : Number(value)
  if (!Number.isFinite(days)) return 0
  return Math.max(0, Math.trunc(days))
}
