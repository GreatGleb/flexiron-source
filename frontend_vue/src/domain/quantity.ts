/**
 * Одно правило округления для складских количеств.
 *
 * Складывать метры в плавающей точке — значит однажды показать 99.73700000000001:
 * 102.24 − 2.503 даёт именно это. Число уходит в хранилище и потом в таблицу, где
 * читается как ошибка данных, хотя это ошибка сложения.
 *
 * Шесть знаков — заведомо больше любой складской точности (микрон на метре) и
 * заведомо меньше того, где начинается мусор двоичной дроби.
 */
export function roundQuantity(value: number): number {
  return Math.round(value * 1e6) / 1e6
}
