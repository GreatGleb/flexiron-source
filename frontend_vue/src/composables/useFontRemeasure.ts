import { onMounted, onBeforeUnmount, nextTick } from 'vue'

/**
 * Повторить замер раскладки, когда доедет веб-шрифт.
 *
 * Зачем это вообще нужно. Браузер сам перерисовывает всё, что считает он: текст
 * перетечёт, колонки перераспределятся, высота строки пересчитается. Но всё, что
 * посчитал JS и вписал обратно в `style`, — это уже не поток, а решение, и оно
 * остаётся от того шрифта, который был в ходу в момент замера. А в момент
 * монтирования это ещё запасной шрифт: браузер начинает тянуть веб-шрифт при
 * раскладке текста, то есть при той самой раскладке, которую замер и вызывает.
 *
 * Замер 2026-09-24 — ширина строки «Structural Steel Profiles», 12px, одна
 * страница, два прогона (шрифты разрешены / оборваны через `route.abort`):
 *
 *   Inter      135px
 *   запасной   138px    — разница 2 %
 *
 * Два подписчика, а не один, и это не перестраховка:
 *
 * - `document.fonts.ready` закрывает шрифт, уже летящий к ЭТОМУ монтированию.
 *   Обещание берётся в `nextTick`, а не сразу: браузер узнаёт о нужде в шрифте
 *   только когда текст раскладывается, и `ready`, прочитанный раньше этого
 *   момента, вправе разрешиться пустым. `nextTick` уводит чтение за все хуки
 *   `onMounted`, поэтому порядок вызова этого композабла в `setup` ни на что не
 *   влияет — полагаться на него было бы ловушкой для следующего вызывающего;
 * - `loadingdone` закрывает начертание, которое начнёт грузиться ПОЗЖЕ: данные
 *   подставили жирный вариант, открылась вкладка с моноширинным. `ready`
 *   разрешается один раз и такого не увидит. Это и страхует случай, когда
 *   `ready` всё-таки разрешился раньше времени.
 *
 * `remeasure` обязан быть идемпотентным — он вызывается произвольное число раз.
 *
 * Правило живёт здесь в одном экземпляре осознанно (Л5): оно уже стоило одного
 * расхождения эталона по РАЗМЕРУ (`AutoResizeTextarea`, 68px против 71px), и
 * второй его экземпляр, записанный чуть иначе, разошёлся бы с первым молча.
 *
 * Где это НЕ нужно — тоже замерено, чтобы никто не добавил «на всякий случай»:
 * `WarehousePage.syncTableRowHeights` вписывает высоты строк, но они прибиты
 * `\.data-table td { height: 40px }` из `erp-base.css`, и при оборванных шрифтах
 * строки те же 40px, расхождений ноль из 25. Проверка, которой нечего поймать,
 * — не проверка.
 */
export function useFontRemeasure(remeasure: () => void) {
  const onFontsLoaded = () => remeasure()

  onMounted(() => {
    if (typeof document === 'undefined' || !document.fonts) return
    document.fonts.addEventListener('loadingdone', onFontsLoaded)
    void nextTick(() => document.fonts.ready.then(onFontsLoaded))
  })

  onBeforeUnmount(() => {
    if (typeof document === 'undefined' || !document.fonts) return
    document.fonts.removeEventListener('loadingdone', onFontsLoaded)
  })
}
