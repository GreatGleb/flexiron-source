/**
 * authToken — единственный источник правила «где лежит токен и как он едет на сервер».
 *
 * Модуль отдельный, а не часть `useAuth.ts`, по одной причине: `useAuth.ts` импортирует
 * `apiPost` из `services/api.ts`, и если `api.ts` начнёт импортировать `useAuth.ts` —
 * получится циклический импорт. Здесь нет ни реактивности, ни vue: чистые функции над
 * хранилищем, пригодные и для композабла, и для сборки запроса.
 *
 * Токен лежит в `localStorage` при «запомнить меня» и в `sessionStorage`, когда галочки не
 * было. Читать надо **оба**: копии, читавшие только `localStorage`, давали 401 всем, кто
 * вошёл без галочки.
 */

export const TOKEN_KEY = 'auth_token'
export const CSRF_KEY = 'csrf_token'

/**
 * Токен сессии из любого из двух хранилищ.
 *
 * Пустая строка — не токен, и отсекается здесь, в источнике. `??` её не отсекает: он
 * срабатывает только на `null` и `undefined`. Потребитель, сравнивающий результат с
 * `null`, на пустой строке решил бы, что человек вошёл. Второе следствие того же
 * недосмотра: пустая строка в одном хранилище заслоняла живой токен в другом.
 */
export function getStoredToken(): string | null {
  return readValue(() => localStorage, TOKEN_KEY) ?? readValue(() => sessionStorage, TOKEN_KEY)
}

/**
 * Значение из хранилища; пустая строка — то же самое, что отсутствие.
 *
 * Хранилища может не быть вовсе, и это не теория: юнит-спеки идут в окружении `node`, где
 * `localStorage` не объявлен, а браузер умеет бросать на обращении к нему в приватном режиме
 * и при запрещённых данных сайта. Раньше эта ветка не всплывала, потому что подпись
 * собиралась только перед `fetch`; теперь она собирается и для мок-ветки, и отсутствие
 * хранилища обязано читаться как «токена нет», а не как падение.
 */
function readValue(read: () => Storage, key: string): string | null {
  try {
    const raw = read().getItem(key)
    return raw !== null && raw !== '' ? raw : null
  } catch {
    return null
  }
}

/**
 * CSRF-токен из любого из двух хранилищ.
 *
 * Пустая строка отсекается так же, как у токена. Сегодня это инертно — сервер CSRF не
 * проверяет нигде, — но правило в файле-единственном-источнике обязано быть одним для обоих
 * значений, иначе следующий потребитель напорется на ту же несимметричность.
 */
export function getStoredCsrf(): string | null {
  return readValue(() => localStorage, CSRF_KEY) ?? readValue(() => sessionStorage, CSRF_KEY)
}

/**
 * Заголовки авторизации для запроса. `undefined`, когда токена нет вовсе — тогда запрос
 * уходит без заголовков, как это и должно быть у публичных роутов (вход, регистрация).
 */
export function authHeaders(): Record<string, string> | undefined {
  const token = getStoredToken()
  if (!token) return undefined
  return {
    Authorization: `Bearer ${token}`,
    'X-CSRF-Token': getStoredCsrf() ?? '',
  }
}
