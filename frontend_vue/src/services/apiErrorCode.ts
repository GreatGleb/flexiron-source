import { ApiRequestError } from '@/types/api'

/**
 * Код отказа в начале текста исключения: `CONFLICT`, `CONFLICT: client has orders`,
 * `UNKNOWN_SORT_KEY: name`. Длина от пяти символов — та же мерка, что у сторожа
 * (`apiErrorCode.guard.ts`, `CODE_LITERAL`), чтобы «код» здесь и «код» там значили одно.
 *
 * Двоеточие — единственный разделитель, который мок вообще употребляет: 12 форм
 * `КОД: подробность` из 113 (`mocks/clients.ts:1133` и одиннадцать похожих), остальные
 * 85 — голый код. Пробел разделителем НЕ считается намеренно: человеческая фраза
 * «VALIDATION failed here» иначе превратилась бы в код `VALIDATION`.
 */
const CODE_AT_START = /^([A-Z][A-Z0-9_]{4,})(?::|$)/

/**
 * Машинный код отказа — из поля, а не из текста.
 *
 * Правило §2 общих соглашений: «отказ несёт код, а не текст». У настоящего API код лежит в
 * `ApiRequestError.code` (`types/api.ts:29`, заполняет `unwrap()` — `api.ts:149-154`,
 * `:161-165`), а `message` — человеческая фраза сервера, которую сервер вправе переписать
 * в любой момент. Ветка, сравнивающая `e.message` с кодом, против сервера не срабатывает
 * никогда: осмысленное сообщение превращается в общее «что-то пошло не так».
 *
 * **Откат на `message` — переходный, и он тут не для красоты.** В мок-режиме `unwrap()`
 * не вызывается вовсе (`api.ts:179-182`: ветка `USE_MOCKS` возвращает `getMock` до
 * `fetch`), а мок бросает голый `Error(код)` в 211 местах. Убрать откат раньше, чем мок
 * переведут на `ApiRequestError`, значит сломать разбор ошибок разом во всех доменах.
 * Обратный порядок безопасен: `code` у голого `Error` отсутствует, и откат срабатывает
 * сам.
 *
 * **Откат отрезает подробность от кода** — в этом его отличие от прежней редакции. Мок
 * бросает `CONFLICT: client has orders`, то есть кладёт машинный код ВНУТРЬ текста, и
 * раньше каждый вызывающий выпутывался сам: сравнивал подстрокой. Подстрока — сравнение,
 * которое молча даёт ложное «да» на вложенных кодах (`BATCH_NOT_FOUND` внутри
 * `RETURN_BATCH_NOT_FOUND`), и держалось оно ручной дисциплиной порядка строк. Резка
 * происходит здесь, один раз, и все вызывающие сравнивают равенством.
 *
 * Возвращается строка, а не `string | null`, чтобы вызывающему не приходилось заводить
 * второй сторож: «кода нет» и «код не тот» для него одно и то же событие.
 */
export function errorCode(error: unknown): string {
  if (error instanceof ApiRequestError && error.code) return error.code
  const text = error instanceof Error ? error.message : String(error)
  // Текст без кода в начале возвращается целиком: `Request failed (500)` — это не код,
  // и урезать его не до чего. Вызывающий всё равно промахнётся мимо своей таблицы и
  // покажет запасное сообщение — то же, что и раньше.
  return CODE_AT_START.exec(text)?.[1] ?? text
}

/**
 * Код отказа → ключ перевода по таблице домена.
 *
 * Сопоставление **равенством**. Подстрока, которая стояла здесь до 2026-09-12, требовала
 * от §2 невыполнимого — «ни один код не является подстрокой другого» — и перекладывала
 * соблюдение на порядок строк в таблице у каждого вызывающего. Требование уже нарушено
 * массово (находка в баг-файле соглашений), так что подстрока была не строгой проверкой,
 * а отложенной ошибкой сопоставления. Форму `КОД: подробность`, ради которой подстроку
 * заводили, снимает `errorCode` выше.
 *
 * Таблица передаётся вызывающим, а не живёт здесь: коды доменные, и общий словарь на
 * семнадцать доменов был бы ровно тем вторым источником правила, от которого лечит Л5.
 * Здесь живёт само правило — один раз.
 */
export function errorMessageKey(
  error: unknown,
  keys: ReadonlyArray<readonly [string, string]>,
  fallback: string,
): string {
  const code = errorCode(error)
  for (const [candidate, key] of keys) {
    if (code === candidate) return key
  }
  return fallback
}
