// Молчание агента (обрыв, 529) — не провал: повторяем, счётчик попыток не трогаем.
async function tryAgent(prompt, opts, attempts = MAX_SILENT + 1) {
  for (let i = 0; i < attempts; i++) {
    const r = await agent(prompt, opts)
    if (r) return r
    if (i + 1 < attempts) log(`${opts.label}: молчание, повтор ${i + 2}/${attempts}`)
  }
  return null
}

