/**
 * Замер расхода без коммита — для волн, которые ничего не произвели.
 * Отдельный дешёвый агент: одна команда, минимум рассуждения.
 */
async function measureSpend(title, phaseName) {
  const m = await tryAgent(
    [
      `Одна команда, ничего больше: python3 ${BRIEFS}/расход.py`,
      'Верни первую строку вывода в tokensTotal, вторую в cacheReadTotal.',
      'Ничего не читай, не меняй, не коммить. commits = [], treeClean = true.',
    ].join('\n'),
    { schema: COMMIT, label: `замер расхода: ${title}`, phase: phaseName, effort: 'low' },
    1,
  )
  if (m && m.tokensTotal) {
    spent = m.tokensTotal - BASELINE
    spentCacheRead = (m.cacheReadTotal || 0) - CACHE_BASELINE
    if (CACHE_READ_WEIGHT) spent += Math.round(spentCacheRead * CACHE_READ_WEIGHT)
    log(`замер после «${title}»: ${budgetLine()}`)
  }
  return m ? m.tokensTotal : 0
}

// Скептик — только после зелёного машинного гейта. Он читает тот же контекст, то есть
// удваивает цену задачи; звать его на красную спеку незачем.
async function judged(w, what, phaseName, judgePrompt) {
  if (!w || w.status !== 'сделано') return w
  if (!w.gateGreen) {
    log(`${what}: гейт красный — скептика не зову, задача провалена`)
    return { ...w, status: 'провалено', notes: `гейт красный: ${w.gate || w.notes}` }
  }
  const j = await tryAgent(judgePrompt(w), { schema: JUDGE, label: `скептик: ${what}`, phase: phaseName, effort: 'high' })
  if (!j) return w
  if (j.refuted) {
    log(`${what}: скептик отклонил — ${j.reason}`)
    return { ...w, status: 'провалено', notes: `скептик: ${j.reason}`, files: w.files }
  }
  return w
}

