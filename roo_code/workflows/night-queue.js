function fixerPrompt(defects, round) {
  return [
    branchGuard(BRANCH),
    contextRules(),
    `ПОЧИНКА РАСКРОЯ, круг ${round}. Ты НЕ автор нарезки и НЕ критик — третий.`,
    '',
    'Критик нашёл дефекты класса «артефакт». Почини ровно их, ничего сверх:',
    JSON.stringify(defects, null, 1),
    '',
    'Правила, без которых починка навредит:',
    '1. Правь ТОЛЬКО файлы в ' + BRIEFS + '. Скрипт воркфлоу, код приложения и файлы',
    '   репозитория НЕ ТРОГАЙ ни при каких обстоятельствах.',
    '2. Не переделывай то, о чём критик не говорил: у нарезки есть верные части, и',
    '   переписывание верного теряет найденное.',
    '3. Правило нарезчика прежнее и главное: копировать дословно с файл:строка можно,',
    '   формулировать своими словами — нельзя.',
    '4. Починил — прогони ту самую команду, которой критик доказал дефект, и покажи,',
    '   что она теперь даёт другое. Без этого починка недоказуема.',
    '',
    'files = что изменил. git НЕ ТРОГАЙ — артефакты вне репозитория, коммитить нечего.',
  ].join('\n')
}

let cutClean = false
let scriptDefects = []
let lastCritic = null
for (let round = 1; round <= CUT_ROUNDS; round++) {
  const critic = await tryAgent(criticPrompt(round), {
    schema: CRITIC,
    label: `критик раскроя, круг ${round}`,
    phase: 'Приёмка раскроя',
    effort: 'high',
  })
  if (!critic) {
    log(`приёмка раскроя: критик круга ${round} промолчал — дальше идти вслепую нельзя`)
    break
  }
  lastCritic = critic
  const defects = critic.defects || []
  // Дефекты скрипта копим по всем кругам: починка их не трогает, они уходят человеку.
  for (const d of defects) if (d.blame === 'скрипт') scriptDefects.push({ ...d, round })
  const artifactDefects = defects.filter((d) => d.blame === 'артефакт')

  if (!defects.length) {
    cutClean = true
    log(`приёмка раскроя: круг ${round} чист`)
    break
  }
  log(
    `приёмка раскроя, круг ${round}: дефектов ${defects.length} ` +
      `(артефакт ${artifactDefects.length}, скрипт ${defects.length - artifactDefects.length})`,
  )
  for (const d of defects) log(`  [${d.blame}] ${d.what} — ${d.where}`)

  if (!artifactDefects.length) {
    // Чинить нечего: всё, что нашли, — про скрипт. Следующий круг даст то же самое.
    log('приёмка раскроя: все дефекты про скрипт, автоматическая починка бессильна — круги прекращены')
    break
  }
  /*
   * CUT_ROUNDS — число ПОЧИНОК, а не проверок, и это исправление дефекта С10 пробного
   * прогона 2026-09-12. Было: критик → (последний круг? break) → починка. То есть последний
   * критик работал вхолостую, и найденные им четыре дефекта артефактов остались в артефактах,
   * хотя три правились одной строкой каждый. Стало: починка идёт на каждом круге, включая
   * последний, а после цикла встаёт контрольный критик — его находки уже не чинятся, но
   * попадают в диагноз честной строкой «осталось», а не пропадают.
   */
  const fix = await tryAgent(fixerPrompt(artifactDefects, round), {
    schema: WORK,
    label: `починка раскроя, круг ${round}`,
    phase: 'Приёмка раскроя',
    effort: 'high',
  })
  if (!fix || fix.status !== 'сделано') {
    log(`приёмка раскроя: починка круга ${round} не сошлась — ${fix ? fix.notes : 'молчание'}`)
    break
  }
}

// Контрольный критик: цикл кончился починкой, и что она дала — никто ещё не смотрел.
