// Фиксатор фазы: единственный, кто трогает git. По коммиту на задачу, серийно.
async function commitWave(title, results, phaseName) {
  const done = results.filter((r) => r && r.status === 'сделано' && r.files && r.files.length)
  // Даже когда коммитить нечего, замер нужен: провалившаяся волна тоже потратила токены,
  // и не заметить этого — значит проехать потолок на фазе, которая ничего не дала.
  if (!done.length) {
    const m = await measureSpend(title, phaseName)
    return { commits: [], treeClean: true, tokensTotal: m, notes: 'коммитить нечего' }
  }
  const c = await tryAgent(
    [
      branchGuard(BRANCH),
      `ФИКСАТОР волны «${title}». Ты единственный в этой волне, кто трогает git.`,
      'Рабочие агенты писали файлы и git не касались — параллельные коммиты дерутся за index.lock.',
      '',
      'Задачи волны и их файлы:',
      JSON.stringify(done.map((r) => ({ task: r.task, files: r.files })), null, 1),
      '',
      'Порядок: по КОММИТУ НА ЗАДАЧУ, серийно, в порядке списка.',
      '  git add -- <файлы этой задачи>   (именно перечисленные, НЕ git add -A и НЕ git add .)',
      '  git commit -m "<тип>(<область>): <что сделано> — <задача>"',
      'Пуша нет. Заголовок на русском, как в истории ветки: git log --oneline -5 покажет стиль.',
      '',
      'Если git status --short после всех коммитов не пуст — назови в notes, ЧТО осталось',
      'и почему ты это не взял. Молча оставлять хвост нельзя: следующая фаза увидит грязное',
      'дерево и сочтёт его чужой работой.',
      `Допиши в ${JOURNAL} строку на каждую задачу: задача · итог · доказательство · SHA.`,
      '',
      'ПОСЛЕДНИМ ДЕЙСТВИЕМ — замер расхода, он решает, жить прогону дальше или свернуться:',
      `  python3 ${BRIEFS}/расход.py`,
      'Первая строка → tokensTotal, вторая → cacheReadTotal. Числа отдай как есть, без правок:',
      'скрипт сам вычтет нулевую отметку. Счётчик не отработал → скажи это в notes и верни 0 —',
      'прогон тогда остановится, и это правильно: потолок без замера не потолок.',
      '',
      'Верни SHA всех коммитов.',
    ].join('\n'),
    { schema: COMMIT, label: `фиксатор: ${title}`, phase: phaseName, effort: 'low' },
  )
  if (c) {
    if (c.tokensTotal) {
      spent = c.tokensTotal - BASELINE
      spentCacheRead = (c.cacheReadTotal || 0) - CACHE_BASELINE
      if (CACHE_READ_WEIGHT) spent += Math.round(spentCacheRead * CACHE_READ_WEIGHT)
    }
    log(
      `фиксатор ${title}: коммитов ${c.commits.length}` +
        (c.treeClean ? '' : ', ДЕРЕВО НЕ ЧИСТОЕ — ' + c.notes) +
        `; ${budgetLine()}`,
    )
    if (mustStop()) log(`ПОТОЛОК РАСХОДА ДОСТИГНУТ после «${title}» — остальные фазы не запускаются, иду в финал.`)
    else if (!canStart()) log(`Порог новых задач пройден после «${title}» — новые задачи не стартуют, начатые доделываются.`)
    else if (!canRetry()) log(`Порог вторых попыток пройден после «${title}» — провал теперь окончателен.`)
  }
  return c || { commits: [], treeClean: false, tokensTotal: 0, notes: 'фиксатор промолчал' }
}

/**
 * Замер расхода без коммита — для волн, которые ничего не произвели.
 * Отдельный дешёвый агент: одна команда, минимум рассуждения.
 */
async function measureSpend(title, phaseName) {
  const m = await tryAgent(
    [
      `Одна команда, ничего больше: python3 ${BRIEFS}/расход.py`,
      'Верни первую строку вывода в tokensTotal, вторую в cacheReadTotal.',
      'Ничего не читай, не меняй, не коммить. commits = [], treeClean = true.',
    ].join('\n'),
    { schema: COMMIT, label: `замер расхода: ${title}`, phase: phaseName, effort: 'low' },
    1,
  )
  if (m && m.tokensTotal) {
    spent = m.tokensTotal - BASELINE
    spentCacheRead = (m.cacheReadTotal || 0) - CACHE_BASELINE
    if (CACHE_READ_WEIGHT) spent += Math.round(spentCacheRead * CACHE_READ_WEIGHT)
    log(`замер после «${title}»: ${budgetLine()}`)
  }
  return m ? m.tokensTotal : 0
}

// Скептик — только после зелёного машинного гейта. Он читает тот же контекст, то есть
// удваивает цену задачи; звать его на красную спеку незачем.
async function judged(w, what, phaseName, judgePrompt) {
  if (!w || w.status !== 'сделано') return w
  if (!w.gateGreen) {
    log(`${what}: гейт красный — скептика не зову, задача провалена`)
    return { ...w, status: 'провалено', notes: `гейт красный: ${w.gate || w.notes}` }
  }
  const j = await tryAgent(judgePrompt(w), { schema: JUDGE, label: `скептик: ${what}`, phase: phaseName, effort: 'high' })
  if (!j) return w
  if (j.refuted) {
    log(`${what}: скептик отклонил — ${j.reason}`)
    return { ...w, status: 'провалено', notes: `скептик: ${j.reason}`, files: w.files }
  }
  return w
}

